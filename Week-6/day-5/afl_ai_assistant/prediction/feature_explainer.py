DISCLAIMER = "\n\n> **Disclaimer:** This prediction is generated by a machine learning model and represents a probability, not a certainty."

def explain_match_prediction(prediction: dict, home: str, away: str) -> str:
    prob = prediction['home_win_probability'] * 100
    winner = prediction['predicted_winner']
    features = ["recent form", "home-ground advantage", "scoring efficiency"]
    
    exp = f"{winner} has a {prob:.1f}% predicted chance of winning against {away if winner == home else home} based on {', '.join(features)}."
    return exp + DISCLAIMER

def explain_player_prediction(prediction: dict, team: str) -> str:
    player = prediction['predicted_top_player']
    score = prediction['predicted_score']
    features = ["historical average", "opponent defensive rating"]
    
    exp = f"{player} is predicted to be the top player for {team} with an estimated fantasy score of {score:.1f}, based on {', '.join(features)}."
    return exp + DISCLAIMER
